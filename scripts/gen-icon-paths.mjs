// Writes src/components/icon-paths.ts: the light and fill drawings of every
// Phosphor icon src/components/icons.tsx names, and nothing else.
//
// Why: each @phosphor-icons/react component ships all six weights (thin, light,
// regular, bold, fill, duotone). The site draws only light, and fill for
// `fill-current`, so importing the components put ~four unused drawings per
// icon into the first-paint bundle. Rerun after adding an icon to icons.tsx:
//
//     node scripts/gen-icon-paths.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";

const require = createRequire(import.meta.url);
const React = require("react");
const { renderToStaticMarkup } = require("react-dom/server");

const ICONS = "src/components/icons.tsx";
const OUT = "src/components/icon-paths.ts";
const DEFS = "node_modules/@phosphor-icons/react/dist/defs";

// Every `make("<PhosphorName>", "<SiteName>")` in icons.tsx.
const names = [...new Set([...readFileSync(ICONS, "utf8").matchAll(/make\("([A-Za-z0-9]+)",/g)].map((m) => m[1]))].sort();
if (names.length === 0) throw new Error(`no make("<Name>", …) calls found in ${ICONS}`);

const entries = [];
for (const name of names) {
  const { default: weights } = await import(pathToFileURL(`${DEFS}/${name}.es.js`).href);
  const svg = (weight) => {
    const node = weights.get(weight);
    if (!node) throw new Error(`${name} has no "${weight}" weight`);
    return renderToStaticMarkup(React.createElement(React.Fragment, null, node));
  };
  entries.push(`  ${name}: [${JSON.stringify(svg("light"))}, ${JSON.stringify(svg("fill"))}],`);
}

writeFileSync(
  OUT,
  `// SPDX-License-Identifier: Hippocratic-3.0
// GENERATED by scripts/gen-icon-paths.mjs from @phosphor-icons/react — do not edit.
// [light, fill] inner SVG markup on Phosphor's 256x256 grid.
export const ICON_PATHS: Record<string, readonly [light: string, fill: string]> = {
${entries.join("\n")}
};
`,
);
console.log(`${OUT}: ${names.length} icons`);
