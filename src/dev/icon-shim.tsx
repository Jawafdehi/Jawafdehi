import { forwardRef, createElement } from "react";
import * as Lucide from "lucide-react-real";
import * as Ph from "@phosphor-icons/react";
import * as Tb from "@tabler/icons-react";
import * as Io from "iconoir-react";
import * as Hg from "@hugeicons/core-free-icons";
import { HugeiconsIcon } from "@hugeicons/react";

import MAP from "@/dev/icon-map.json";
import { useIconLib } from "@/dev/icon-lib-store";

export * from "lucide-react-real";

function make(name) {
  const Base = Lucide[name];
  const map = MAP[name] ?? {};
  const Icon = forwardRef(function ShimIcon(props, ref) {
    const lib = useIconLib();
    const { size, strokeWidth, absoluteStrokeWidth, color, ...rest } = props;
    const px = size ?? 24;
    if (lib === "lucide-thin") return createElement(Base, { ref, ...props, strokeWidth: 1.5 });
    if (lib === "phosphor" && Ph[map.ph]) return createElement(Ph[map.ph], { ref, size: px, weight: "light", color, ...rest });
    if (lib === "tabler" && Tb[map.tb]) return createElement(Tb[map.tb], { ref, size: px, stroke: 1.5, color, ...rest });
    if (lib === "iconoir" && Io[map.io]) return createElement(Io[map.io], { ref, width: px, height: px, strokeWidth: 1.5, color, ...rest });
    if (lib === "hugeicons" && Hg[map.hg]) return createElement(HugeiconsIcon, { ref, icon: Hg[map.hg], size: px, strokeWidth: 1.5, color, ...rest });
    return createElement(Base, { ref, ...props });
  });
  Icon.displayName = name;
  return Icon;
}

